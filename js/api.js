/**
 * Tadka & Trends — API Service Layer & Java Spring Boot REST Integration Bridge
 *
 * Currently backed by browser `localStorage` for immediate academic demo execution.
 * To connect to the Java Spring Boot + MySQL backend later:
 *   1. Set `USE_BACKEND_API = true`
 *   2. Point `API_BASE_URL` to your Spring Boot server (e.g. `http://localhost:8080/api`)
 *   3. No UI code in `js/app.js` needs to change.
 */

import { DEFAULT_RECIPES, DAYS_OF_WEEK } from './data.js';

export const USE_BACKEND_API = false;
export const API_BASE_URL = 'http://localhost:8080/api';

const STORAGE_KEYS = {
  RECIPES: 'tadka_trends_recipes_v1',
  FAVORITES: 'tadka_trends_favorites_v1',
  COOKED_HISTORY: 'tadka_trends_cooked_v1',
  USER_SESSION: 'tadka_trends_user_v1',
  TASTE_PROFILE: 'tadka_trends_taste_profile_v1',
  MEAL_PLAN: 'tadka_trends_meal_plan_v1',
  GROCERY_CHECKS: 'tadka_trends_grocery_checks_v1'
};

function createEmptyWeeklyPlan() {
  const weekly = {};
  DAYS_OF_WEEK.forEach((day) => {
    weekly[day] = { Breakfast: null, Lunch: null, Dinner: null };
  });
  return weekly;
}

function createDefaultMealPlan() {
  return {
    daily: { Breakfast: null, Lunch: null, Dinner: null },
    weekly: createEmptyWeeklyPlan(),
    lastAutoGeneratedAt: null
  };
}

function readStorage(key, fallback) {
  try {
    const raw = localStorage.getItem(key);
    return raw ? JSON.parse(raw) : fallback;
  } catch {
    return fallback;
  }
}

function writeStorage(key, value) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    // Ignore storage quota issues in restricted environments
  }
}

export function ensureInitialData() {
  const existing = readStorage(STORAGE_KEYS.RECIPES, null);
  if (!Array.isArray(existing) || existing.length === 0) {
    writeStorage(STORAGE_KEYS.RECIPES, DEFAULT_RECIPES);
  }
  if (!readStorage(STORAGE_KEYS.FAVORITES, null)) {
    writeStorage(STORAGE_KEYS.FAVORITES, [1, 6, 11]);
  }
  if (!readStorage(STORAGE_KEYS.COOKED_HISTORY, null)) {
    writeStorage(STORAGE_KEYS.COOKED_HISTORY, []);
  }
  if (!readStorage(STORAGE_KEYS.MEAL_PLAN, null)) {
    writeStorage(STORAGE_KEYS.MEAL_PLAN, createDefaultMealPlan());
  }
}

/**
 * GET /api/recipes
 */
export async function fetchAllRecipes() {
  if (USE_BACKEND_API) {
    const res = await fetch(`${API_BASE_URL}/recipes`);
    if (!res.ok) throw new Error('Failed to fetch recipes from backend');
    return res.json();
  }
  ensureInitialData();
  return readStorage(STORAGE_KEYS.RECIPES, [...DEFAULT_RECIPES]);
}

/**
 * GET /api/recipes/{id}
 */
export async function fetchRecipeById(id) {
  if (USE_BACKEND_API) {
    const res = await fetch(`${API_BASE_URL}/recipes/${encodeURIComponent(id)}`);
    if (!res.ok) throw new Error('Recipe not found');
    return res.json();
  }
  const recipes = await fetchAllRecipes();
  return recipes.find((r) => Number(r.id) === Number(id)) || null;
}

/**
 * GET /api/recipes/search?heroIngredient=&mealTime=&cuisineStyle=&diet=&maxTime=&q=
 */
export async function searchRecipes(filters = {}) {
  if (USE_BACKEND_API) {
    const params = new URLSearchParams();
    Object.entries(filters).forEach(([k, v]) => {
      if (v && v !== 'All') params.set(k, String(v));
    });
    const res = await fetch(`${API_BASE_URL}/recipes/search?${params.toString()}`);
    if (!res.ok) throw new Error('Recipe search failed');
    return res.json();
  }

  const all = await fetchAllRecipes();
  const query = (filters.q || '').trim().toLowerCase();

  return all.filter((recipe) => {
    if (filters.heroIngredient && filters.heroIngredient !== 'All') {
      if (recipe.heroIngredient !== filters.heroIngredient) return false;
    }
    if (filters.mealTime && filters.mealTime !== 'All') {
      if (recipe.mealTime !== filters.mealTime) return false;
    }
    if (filters.cuisineStyle && filters.cuisineStyle !== 'All') {
      if (recipe.cuisineStyle !== filters.cuisineStyle) return false;
    }
    if (filters.diet && filters.diet !== 'All') {
      if (recipe.diet !== filters.diet) return false;
    }
    if (filters.maxTime && filters.maxTime !== 'All') {
      const total = Number(recipe.prepTime) + Number(recipe.cookTime);
      if (total > Number(filters.maxTime)) return false;
    }
    if (query) {
      const inName = recipe.name.toLowerCase().includes(query);
      const inDesc = recipe.description.toLowerCase().includes(query);
      const inHero = recipe.heroIngredient.toLowerCase().includes(query);
      const inIngredients = (recipe.ingredients || []).some((ing) =>
        ing.item.toLowerCase().includes(query)
      );
      if (!inName && !inDesc && !inHero && !inIngredients) return false;
    }
    return true;
  });
}

/**
 * POST /api/recipes
 */
export async function createRecipe(recipePayload) {
  if (USE_BACKEND_API) {
    const res = await fetch(`${API_BASE_URL}/recipes`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(recipePayload)
    });
    if (!res.ok) throw new Error('Failed to create recipe');
    return res.json();
  }

  const recipes = await fetchAllRecipes();
  const maxId = recipes.reduce((max, r) => Math.max(max, Number(r.id) || 0), 0);
  const newRecipe = {
    ...recipePayload,
    id: maxId + 1,
    featured: false,
    createdAt: new Date().toISOString().slice(0, 10)
  };
  const updated = [newRecipe, ...recipes];
  writeStorage(STORAGE_KEYS.RECIPES, updated);
  return newRecipe;
}

/**
 * PUT /api/recipes/{id}
 */
export async function updateRecipe(id, recipePayload) {
  if (USE_BACKEND_API) {
    const res = await fetch(`${API_BASE_URL}/recipes/${encodeURIComponent(id)}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(recipePayload)
    });
    if (!res.ok) throw new Error('Failed to update recipe');
    return res.json();
  }

  const recipes = await fetchAllRecipes();
  let updatedItem = null;
  const updated = recipes.map((r) => {
    if (Number(r.id) === Number(id)) {
      updatedItem = { ...r, ...recipePayload, id: Number(id) };
      return updatedItem;
    }
    return r;
  });
  writeStorage(STORAGE_KEYS.RECIPES, updated);
  return updatedItem;
}

/**
 * DELETE /api/recipes/{id}
 */
export async function deleteRecipe(id) {
  if (USE_BACKEND_API) {
    const res = await fetch(`${API_BASE_URL}/recipes/${encodeURIComponent(id)}`, {
      method: 'DELETE'
    });
    if (!res.ok) throw new Error('Failed to delete recipe');
    return true;
  }

  const recipes = await fetchAllRecipes();
  const targetId = Number(id);
  writeStorage(
    STORAGE_KEYS.RECIPES,
    recipes.filter((r) => Number(r.id) !== targetId)
  );

  // Clean up references in favorites and meal plans
  const favs = getFavorites().filter((fid) => Number(fid) !== targetId);
  writeStorage(STORAGE_KEYS.FAVORITES, favs);

  const plan = getMealPlan();
  ['Breakfast', 'Lunch', 'Dinner'].forEach((slot) => {
    if (Number(plan.daily[slot]) === targetId) plan.daily[slot] = null;
  });
  DAYS_OF_WEEK.forEach((day) => {
    ['Breakfast', 'Lunch', 'Dinner'].forEach((slot) => {
      if (Number(plan.weekly[day]?.[slot]) === targetId) plan.weekly[day][slot] = null;
    });
  });
  writeStorage(STORAGE_KEYS.MEAL_PLAN, plan);
  return true;
}

export async function resetDemoRecipes() {
  writeStorage(STORAGE_KEYS.RECIPES, DEFAULT_RECIPES);
  return [...DEFAULT_RECIPES];
}

/**
 * GET /api/users/{id}/taste-profile
 */
export async function fetchTasteProfile(userId = 'demo-user') {
  if (USE_BACKEND_API) {
    const res = await fetch(`${API_BASE_URL}/users/${encodeURIComponent(userId)}/taste-profile`);
    if (!res.ok) throw new Error('Failed to load taste profile');
    return res.json();
  }

  const cookedHistory = getCookedHistory();
  const recipes = await fetchAllRecipes();
  const user = getUserSession();
  return computeTasteProfileFromHistory(cookedHistory, recipes, user);
}

export function computeTasteProfileFromHistory(cookedHistory, recipes, user) {
  const recipeMap = new Map(recipes.map((r) => [Number(r.id), r]));
  const cookedEntries = cookedHistory
    .map((entry) => ({
      ...entry,
      recipe: recipeMap.get(Number(entry.recipeId))
    }))
    .filter((item) => Boolean(item.recipe));

  const totalCooked = cookedEntries.length;

  if (totalCooked === 0) {
    return {
      totalCooked: 0,
      statusLabel: 'New Foodie — Cook 1 dish to detect taste',
      indianPercent: 50,
      genZPercent: 50,
      dominantCuisine: 'Balanced',
      preferredSpice: 'Medium',
      spiceScore: 55,
      vegPercent: user?.dietPreference === 'Non-Veg' ? 40 : 100,
      dietPreference: user?.dietPreference || 'All',
      favoriteHeroIngredient: 'Paneer',
      heroBreakdown: [],
      cookedEntries: []
    };
  }

  let indianCount = 0;
  let genZCount = 0;
  let vegCount = 0;
  let spiceSum = 0;
  const heroCounts = {};

  const spiceWeightMap = {
    'Sweet / No Spice': 15,
    Mild: 35,
    Medium: 65,
    Spicy: 95
  };

  cookedEntries.forEach(({ recipe }) => {
    if (recipe.cuisineStyle === 'Indian Classic') indianCount += 1;
    else genZCount += 1;

    if (recipe.diet === 'Veg') vegCount += 1;

    spiceSum += spiceWeightMap[recipe.spiceLevel] ?? 55;
    heroCounts[recipe.heroIngredient] = (heroCounts[recipe.heroIngredient] || 0) + 1;
  });

  const indianPercent = Math.round((indianCount / totalCooked) * 100);
  const genZPercent = 100 - indianPercent;
  const vegPercent = Math.round((vegCount / totalCooked) * 100);
  const spiceScore = Math.round(spiceSum / totalCooked);

  let preferredSpice = 'Medium';
  if (spiceScore < 30) preferredSpice = 'Mild / Sweet';
  else if (spiceScore < 50) preferredSpice = 'Mild';
  else if (spiceScore < 75) preferredSpice = 'Medium';
  else preferredSpice = 'Spicy';

  let dominantCuisine = 'Balanced Fusion';
  if (indianPercent >= 65) dominantCuisine = 'Indian Classic';
  else if (genZPercent >= 65) dominantCuisine = 'Gen-Z / Continental';

  const heroBreakdown = Object.entries(heroCounts)
    .map(([ingredient, count]) => ({
      ingredient,
      count,
      percent: Math.round((count / totalCooked) * 100)
    }))
    .sort((a, b) => b.count - a.count);

  const favoriteHeroIngredient = heroBreakdown[0]?.ingredient || 'Paneer';

  let persona = 'Balanced Tadka & Trends';
  if (dominantCuisine === 'Indian Classic' && spiceScore >= 70) persona = 'Spice-Loving Desi Foodie';
  else if (dominantCuisine === 'Indian Classic') persona = 'Traditional Family Tadka';
  else if (dominantCuisine === 'Gen-Z / Continental' && spiceScore >= 70) persona = 'Fiery Gen-Z Trendsetter';
  else if (dominantCuisine === 'Gen-Z / Continental') persona = 'Modern Cafe Explorer';
  else if (spiceScore >= 75) persona = 'Heat-Seeking Fusion Cook';

  const statusLabel = `${persona} · ${totalCooked} ${totalCooked === 1 ? 'dish' : 'dishes'} cooked`;

  return {
    totalCooked,
    statusLabel,
    indianPercent,
    genZPercent,
    dominantCuisine,
    preferredSpice,
    spiceScore,
    vegPercent,
    dietPreference: user?.dietPreference || (vegPercent === 100 ? 'Veg' : 'All'),
    favoriteHeroIngredient,
    heroBreakdown,
    cookedEntries
  };
}

/**
 * POST /api/meal-plans
 */
export async function saveMealPlan(mealPlan, userId = 'demo-user') {
  if (USE_BACKEND_API) {
    const res = await fetch(`${API_BASE_URL}/meal-plans`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ userId, mealPlan })
    });
    if (!res.ok) throw new Error('Failed to save meal plan');
    return res.json();
  }

  writeStorage(STORAGE_KEYS.MEAL_PLAN, mealPlan);
  return mealPlan;
}

export function getMealPlan() {
  const stored = readStorage(STORAGE_KEYS.MEAL_PLAN, null);
  if (!stored || !stored.daily || !stored.weekly) {
    const fresh = createDefaultMealPlan();
    writeStorage(STORAGE_KEYS.MEAL_PLAN, fresh);
    return fresh;
  }
  return stored;
}

export function getFavorites() {
  return readStorage(STORAGE_KEYS.FAVORITES, [1, 6, 11]);
}

export function toggleFavoriteId(recipeId) {
  const id = Number(recipeId);
  const current = getFavorites();
  const exists = current.includes(id);
  const next = exists ? current.filter((x) => x !== id) : [id, ...current];
  writeStorage(STORAGE_KEYS.FAVORITES, next);
  return { favorites: next, isFavorite: !exists };
}

export function getCookedHistory() {
  return readStorage(STORAGE_KEYS.COOKED_HISTORY, []);
}

export function recordCookedDish(recipeId) {
  const id = Number(recipeId);
  const history = getCookedHistory();
  const entry = {
    recipeId: id,
    cookedAt: new Date().toISOString()
  };
  const updated = [entry, ...history];
  writeStorage(STORAGE_KEYS.COOKED_HISTORY, updated);
  return updated;
}

export function clearTasteHistory() {
  writeStorage(STORAGE_KEYS.COOKED_HISTORY, []);
  return [];
}

